-- FASTA2GO - extraction stage schema (DuckDB).
--
-- One row per FASTA record in `proteins`; every other table refines it.
-- Keys are always (source_file, fasta_id) so the original record stays
-- traceable and re-running the ingestion can never duplicate a protein.

CREATE TABLE IF NOT EXISTS proteins (
    source_file       VARCHAR   NOT NULL,
    fasta_id          VARCHAR   NOT NULL,   -- first token of the header, e.g. sp|P69905|HBA_HUMAN
    fasta_header      VARCHAR   NOT NULL,   -- complete original header, traceability
    uniprot_accession VARCHAR,              -- parsed only from ^(sp|tr)\|[A-Z0-9]+\|
    sequence          VARCHAR   NOT NULL,   -- upper case, whitespace removed, unmodified otherwise
    sequence_length   INTEGER   NOT NULL,
    ingested_at       TIMESTAMP NOT NULL,
    PRIMARY KEY (source_file, fasta_id)
);

-- Physicochemical properties. `feature_version` marks which formula set produced
-- the row, so a formula change recomputes rows instead of mixing definitions.
CREATE TABLE IF NOT EXISTS sequence_features (
    source_file           VARCHAR   NOT NULL,
    fasta_id              VARCHAR   NOT NULL,
    feature_version       INTEGER   NOT NULL,
    canonical_length      INTEGER   NOT NULL,  -- residues among the 20 canonical ones
    noncanonical_residues INTEGER   NOT NULL,  -- X, B, Z, U, O, ... excluded from AAC and physicochemical formulas
    canonical_pairs       INTEGER,             -- adjacent pairs with both residues canonical: DPC denominator
    molecular_weight      DOUBLE,              -- Da (average masses, Biopython)
    isoelectric_point     DOUBLE,
    gravy                 DOUBLE,              -- Kyte & Doolittle hydropathy
    instability_index     DOUBLE,              -- Guruprasad et al.
    aliphatic_index       DOUBLE,              -- Ikai
    aromaticity           DOUBLE,              -- fraction of F + W + Y
    sequence_entropy      DOUBLE,              -- Shannon entropy in bits (max log2(20))
    computed_at           TIMESTAMP NOT NULL,
    PRIMARY KEY (source_file, fasta_id)
);

-- Columns added after the first release: CREATE TABLE IF NOT EXISTS does not
-- touch an existing table, so the migration is explicit (and idempotent).
ALTER TABLE sequence_features ADD COLUMN IF NOT EXISTS canonical_pairs INTEGER;

