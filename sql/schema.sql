-- UniProtKB metadata. A missing row means "never queried"; `status` distinguishes
-- an entry UniProt returned from an accession UniProt does not know.
CREATE TABLE IF NOT EXISTS uniprot_annotations (
    source_file          VARCHAR   NOT NULL,
    fasta_id             VARCHAR   NOT NULL,
    uniprot_accession    VARCHAR   NOT NULL,
    uniprot_id           VARCHAR,              -- UniProtKB entry name, e.g. HBA_HUMAN
    protein_name         VARCHAR,
    gene_names           VARCHAR,              -- semicolon separated
    organism             VARCHAR,
    taxon_id             INTEGER,
    protein_existence    VARCHAR,
    secondary_accessions VARCHAR,              -- semicolon separated
    keywords             VARCHAR,              -- semicolon separated
    function_description VARCHAR,
    subcellular_location VARCHAR,
    source_length        INTEGER,              -- sequence length reported by UniProt
    status               VARCHAR   NOT NULL,
    retrieved_at         TIMESTAMP NOT NULL,
    PRIMARY KEY (source_file, fasta_id),
    CHECK (status IN ('matched', 'not_found'))
);

-- GO annotations exactly as retrieved from UniProt. Derived ancestor relations
-- are NOT stored here: only source annotations belong in this table.
-- Empty evidence_code/evidence_source mean the source did not report evidence.
CREATE TABLE IF NOT EXISTS protein_go_annotations (
    source_file     VARCHAR   NOT NULL,
    fasta_id        VARCHAR   NOT NULL,
    go_id           VARCHAR   NOT NULL,
    aspect          VARCHAR   NOT NULL,   -- biological_process | cellular_component | molecular_function
    go_name         VARCHAR,
    evidence_code   VARCHAR   NOT NULL,
    evidence_source VARCHAR   NOT NULL,
    provenance      VARCHAR,              -- semicolon separated source:id, e.g. PubMed:22516433
    retrieved_at    TIMESTAMP NOT NULL,
    PRIMARY KEY (source_file, fasta_id, go_id, evidence_code, evidence_source)
);

-- Records that could not be imported, or that were imported with a warning.
-- Rewritten on every ingestion of the same source_file.
CREATE TABLE IF NOT EXISTS ingestion_issues (
    source_file VARCHAR   NOT NULL,
    line_number BIGINT,
    fasta_id    VARCHAR,
    issue       VARCHAR   NOT NULL,  -- malformed_header | empty_sequence | duplicate_id | noncanonical_residues | header_without_accession
    detail      VARCHAR,
    detected_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS proteins_accession_idx
    ON proteins (uniprot_accession);
CREATE INDEX IF NOT EXISTS go_annotations_term_idx
    ON protein_go_annotations (go_id);
